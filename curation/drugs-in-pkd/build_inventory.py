#!/usr/bin/env python3
"""
Write evidence-inventory.json from the hand-classified findings in findings.py.

The inventory has the same shape as curation/pkd-bible's, so the seeder can
treat the dossiers alike. Nothing here is machine-classified: every
finding, its relevance, register, lane, card text and date were chosen by
reading the passage.

    python curation/drugs-in-pkd/build_inventory.py
"""

import json
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from findings import F, PACKETS  # noqa: E402

# kind -> (source.type, corpus, lane, register, source_mode)
KINDS = {
    'exegesis_segment': ('exegesis_segment', 'segments.raw_text', 'B', 'A', 'exegesis'),
    'letter':           ('letter', 'letters.body_md', 'E', 'A', 'letter'),
    'interview':        ('interview', 'document_texts.markdown_content', 'E', 'A', 'interview'),
    # Dick's own non-fiction attached to a novel (A Scanner Darkly's Author's
    # Note): his words under his own signature, so lane E, not fiction. The
    # source_mode records the container (it is printed in the novel); the
    # schema allows no 'paratext' mode.
    'paratext':         ('paratext', 'document_texts.markdown_content', 'E', 'A', 'fiction'),
    'fiction':          ('fiction', 'document_texts.markdown_content', 'A', 'A', 'fiction'),
    # Biography is lane D; its source_mode is 'criticism', as for Sutin in the
    # Bible dossier (the schema has no 'biography' mode).
    'biography':        ('biography', 'document_texts.markdown_content', 'D', 'C', 'criticism'),
    'criticism':        ('criticism', 'document_texts.markdown_content', 'C', 'C', 'criticism'),
}


def main():
    evidence = []
    for f in F:
        stype, corpus, lane, register, mode = KINDS[f['kind']]
        src = {'type': stype, 'corpus': corpus, 'id': f['source_id'],
               'citation': f['citation'], 'date': None}
        if stype == 'exegesis_segment':
            src['doc_id'] = None   # resolved from segments by the seeder
        else:
            src['doc_id'] = f['source_id'] if stype != 'letter' else None
        evidence.append({
            'id': f['id'],
            'relevance': 1,
            'register': register,
            'confidence': 'high',
            'source': src,
            'anchor': f['anchor'],
            'window': f['window'],
            'lane': lane,
            'source_mode': mode,
            'claim_type': f['claim_type'],
            'evidence_packet': f['packet'],
            'concepts': f['concepts'],
            'on_public_page': True,
            'editorial_note': f.get('note'),
            'dated': f.get('dated'),
            'dating_basis': f.get('dating_basis'),
            'dating_confidence': f.get('dating_confidence'),
            'card': {'context': f['context'], 'pith': f['pith'],
                     'speaker': f['speaker']},
        })

    inv = {
        'topic': 'drugs-in-pkd',
        'title': 'Drugs in Philip K. Dick',
        'generated_utc': datetime.now(timezone.utc).isoformat(timespec='seconds'),
        'source_of_truth': True,
        'note': ('Generated from findings.py, which is hand-curated. Edit findings.py '
                 'and re-run build_inventory.py; do not edit this file by hand. Raw '
                 'sweep output is regenerable with scripts/research/sweep_corpus.py '
                 '--profile drugs.'),
        'evidence_packets': [
            {'id': pid, 'confidence': conf, 'claim': claim, 'summary': summary}
            for pid, conf, claim, summary in PACKETS
        ],
        'evidence': evidence,
    }
    out = HERE / 'evidence-inventory.json'
    out.write_text(json.dumps(inv, indent=1, ensure_ascii=False), encoding='utf-8')

    lanes = Counter(e['lane'] for e in evidence)
    print(f'{len(evidence)} findings, {len(PACKETS)} packets -> {out.name}')
    print('  lanes', dict(sorted(lanes.items())))
    print('  packets', dict(Counter(e['evidence_packet'] for e in evidence)))


if __name__ == '__main__':
    main()
