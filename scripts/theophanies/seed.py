SCHEMA = """
CREATE TABLE IF NOT EXISTS theophanies (
    theophany_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    slug TEXT NOT NULL UNIQUE,
    date_start TEXT,
    date_end TEXT,
    date_display TEXT,
    date_confidence TEXT,
    date_basis TEXT,
    experience_type TEXT,
    sensory_modality TEXT,
    duration TEXT,
    summary TEXT NOT NULL,
    description TEXT,
    pkd_interpretations TEXT,
    scholar_interpretations TEXT,
    primary_sources TEXT,
    primary_quote TEXT,
    related_theophany_ids TEXT,
    related_works TEXT,
    related_dictionary_terms TEXT,
    related_names TEXT,
    related_segments TEXT,
    contested_status TEXT,
    contradiction_zone TEXT,
    pkd_doubt_evidence TEXT,
    importance TEXT,
    sequence_in_complex INTEGER,
    parent_theophany_id TEXT,
    created_at TEXT,
    updated_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_theo_date ON theophanies(date_start);
CREATE INDEX IF NOT EXISTS idx_theo_parent ON theophanies(parent_theophany_id);

CREATE TABLE IF NOT EXISTS theophany_evidence (
    evidence_id TEXT PRIMARY KEY,
    theophany_id TEXT NOT NULL,
    source_type TEXT NOT NULL,
    source_doc_id TEXT,
    source_seg_id TEXT,
    source_letter_id TEXT,
    page_or_locator TEXT,
    excerpt TEXT,
    excerpt_lane TEXT,
    notes TEXT,
    created_at TEXT,
    FOREIGN KEY (theophany_id) REFERENCES theophanies(theophany_id)
);
CREATE INDEX IF NOT EXISTS idx_theo_ev_theo ON theophany_evidence(theophany_id);
"""


def ensure_schema(con: sqlite3.Connection) -> None:
    con.executescript(SCHEMA)
    cur = con.execute("PRAGMA table_info(biography_events)")
    cols = {r[1] for r in cur.fetchall()}
    if "theophany_id" not in cols:
        con.execute("ALTER TABLE biography_events ADD COLUMN theophany_id TEXT")
    con.commit()


