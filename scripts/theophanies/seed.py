def upsert(con: sqlite3.Connection, t: dict) -> None:
    now = dt.datetime.now(dt.UTC).isoformat(timespec="seconds")
    cols = list(t.keys()) + ["created_at", "updated_at"]
    placeholders = ", ".join(["?"] * len(cols))
    values = [t[k] for k in t.keys()] + [now, now]
    con.execute(
        f"INSERT OR REPLACE INTO theophanies ({', '.join(cols)}) VALUES ({placeholders})",
        values,
    )


def run(db_path: Path) -> None:
    con = sqlite3.connect(db_path)
    ensure_schema(con)
    for t in THEOPHANIES:
        upsert(con, t)
    con.commit()
    cur = con.execute("SELECT count(*) FROM theophanies")
    print(f"[done] {cur.fetchone()[0]} theophanies in DB")
    con.close()


