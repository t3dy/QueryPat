export function locationCategoryTone(category: PKDLocationCategory): string {
  switch (category) {
    case 'Biography':
      return '#7a4b2a'
    case 'Novel setting':
      return '#3a7484'
    case 'Short story setting':
      return '#6a4bb0'
    case 'Institutional site':
      return '#4f7f6d'
    case 'Event':
      return '#b06b22'
    default:
      return '#7b6a56'
  }
}

